import Foundation

/// Display names for the breadcrumb chain.
///
/// The chain is copied from the scan root down to the folder on screen, and one
/// of those folders can have a name a package manager generated. A pnpm store
/// directory for a single dependency measures 120 characters:
///
///     react-native-reanimated@4.5.1_react-native-worklets@0.10.1_@babel+core@7.29.7_supports-_76bc68c0ac7ac91512ade9464ffbf90a
///
/// Drawn whole it pushes every other crumb out of the toolbar. Cropped to a
/// fixed width it reads `react-n…`, which is indistinguishable from every other
/// `react-native-*` folder. Neither is useful, and no allocation of widths fixes
/// it: 120 characters and three neighbours do not fit in a toolbar at any window
/// size the app allows.
///
/// What makes the name unreadable is not its length but what it is made of —
/// versions and a build digest that identify WHICH BUILD of a dependency this is.
/// For a folder breadcrumb, what identifies it is which packages it holds. So the
/// generated parts are dropped and the rest kept.
enum CrumbLayout {
    /// A name longer than this is worth shortening. Ordinary folders never are:
    /// the longest realistic project folder name is well under it.
    static let shorteningThreshold = 72

    /// Whether a name was generated by a package manager rather than chosen by
    /// a person.
    ///
    /// This gate is what keeps the shortening safe. An ordinary folder name can
    /// contain underscores and be long — a ticket title such as
    /// `9) GET article with user reference field, field_user_ref_example` is 70+
    /// characters and full of `_` — and rewriting those to ` + ` would be worse
    /// than the length it was trying to fix. Only a name that carries a version
    /// suffix (`pkg@1.2.3`) AND a pnpm-era marker (a trailing hex digest or a
    /// folded `_@` dependency) is treated as generated.
    static func looksGenerated(_ name: String) -> Bool {
        let hasVersion = name.range(of: #"[A-Za-z0-9][@-]\d+\.\d+"#,
                                    options: .regularExpression) != nil
        guard hasVersion else { return false }
        let hasDigest = name.range(of: #"_[0-9a-f]{20,}$"#,
                                   options: .regularExpression) != nil
        return hasDigest || name.contains("_@")
    }

    /// `name`, with a package manager's generated parts removed when — and only
    /// when — that makes it readable.
    ///
    /// A name that is not recognisably package-manager-generated is returned
    /// exactly as it is, so an ordinary folder can never be mangled by this. It is
    /// a display string: callers keep the real name for tooltips and resolve paths
    /// by node id, so nothing depends on this being reversible.
    static func shorten(_ name: String) -> String {
        guard name.count > shorteningThreshold, looksGenerated(name) else { return name }
        var shortened = name
        // The trailing `_<hex digest>` pnpm appends to distinguish builds. It is
        // an opaque hash: no user has ever recognized a folder by it.
        shortened = shortened.replacingOccurrences(of: #"_[0-9a-f]{20,}$"#, with: "",
                                                   options: .regularExpression)
        // Version suffixes: `pkg@1.2.3` becomes `pkg`. Requires a digit after the
        // `@`, so a scoped package name (`@babel/core`) is never touched.
        shortened = shortened.replacingOccurrences(
            of: #"@\d+(?:[.\-][0-9A-Za-z][0-9A-Za-z.\-]*)+"#,
            with: "", options: .regularExpression)
        // pnpm joins "and these dependencies too" with `_`.
        shortened = shortened.replacingOccurrences(of: "_", with: " + ")
        // The structure was not enough. Bound it, and say so with an ellipsis —
        // the toolbar may still crop further, but a name that ends in "…" reads as
        // cropped while a bare cut reads as corrupt.
        if shortened.count > shorteningThreshold {
            shortened = String(shortened.prefix(shorteningThreshold - 1)) + "…"
        }
        return shortened
    }
}
